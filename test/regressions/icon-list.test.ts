import { describe, expect, it } from "vitest";

import { IconListGenerator } from "../../src/model/generators/icon-list-generator";
import { fixtureHass, loadSyntheticFixture } from "../harness";

const VACUUM = "vacuum.roborock_s7";

async function generatedIcons() {
    const hass = fixtureHass(loadSyntheticFixture());
    return IconListGenerator.generate(hass, VACUUM, "Xiaomi Miio", "en", [], {});
}

describe("autogenerated icons for the synthetic fixture", () => {
    // Captured before the #961 change. The icon list only changes for return_to_base.
    it("generates the common icon list", async () => {
        const icons = await generatedIcons();
        expect(icons.map(icon => `${icon.icon_id}: ${icon.icon ?? "(dynamic)"}`)).toMatchSnapshot();
    });

    it("uses Home Assistant core's return-to-base icon (#961)", async () => {
        const icons = await generatedIcons();
        expect(icons.find(icon => icon.icon_id === "return_to_base")?.icon).toBe("mdi:home-import-outline");
    });
});
