export function isInEditor(card: XiaomiVacuumMapCard): boolean {
    function isInEditor(e: Element): boolean {
        return (e.parentElement?.tagName?.toLowerCase() === "hui-card" && "preview" in (e.parentElement?.attributes ?? []))
            || (e.parentElement?.tagName?.toLowerCase() === "hui-section" && "preview" in (e.parentElement?.attributes ?? []))
            || e.parentElement?.tagName?.toLowerCase() === "hui-card-preview"
            || e.parentElement != null && isInEditor(e.parentElement)
            || e.parentNode?.toString() == "[object ShadowRoot]" && isInEditor((e.getRootNode() as ShadowRoot).host);
    }
    return isInEditor(card);
}

export async function handleAutogeneratedConfigGet(card: XiaomiVacuumMapCard): Promise<void> {
    const event = new Event(EVENT_AUTOGENERATED_CONFIG);
    const additionalPresets = await Promise.all((card.config.additional_presets ?? [])
        .map(async p => await getConfigOfPreset(card, p)));
    (event as any).presetConfig = {
        ...card.config,
        ...await getConfigOfPreset(card, card.config),
        additional_presets: additionalPresets,
    };
    window.dispatchEvent(event);
}

export async function getConfigOfPreset(card: XiaomiVacuumMapCard, preset: CardPresetConfig): Promise<CardPresetConfig> {
    const internalVariables = getInternalVariables(preset)
    const [icons, tiles] = await card._getIconsAndTiles(preset, internalVariables);
    return {
        ...preset,
        icons: JSON.parse(JSON.stringify(icons)),
        tiles: JSON.parse(JSON.stringify(tiles)),
        map_modes: getModes(card, preset).map(m => m.toMapModeConfig()),
    };
}

export function handleRoomsConfigGet(card: XiaomiVacuumMapCard, e: Event): void {
    // EVENT_ROOM_CONFIG_GET is a plain window broadcast, so every mounted card receives it.
    // Only answer when the request names this card's entity/camera; `undefined` keeps legacy
    // callers that dispatch the bare event working as before.
    const request = e as Event & Partial<RoomConfigRequestEventData>;
    const currentPreset = card._getCurrentPreset();
    if (request.entity !== undefined && request.entity !== currentPreset?.entity) {
        return;
    }
    if (request.camera !== undefined && request.camera !== currentPreset?.map_source?.camera) {
        return;
    }
    const event = new Event(EVENT_ROOM_CONFIG);
    (event as any).roomConfig = getRoomsConfig(card, request.requestId);
    window.dispatchEvent(event);
}

export async function handleLovelaceDomEvent(card: XiaomiVacuumMapCard, e: Event): Promise<void> {
    const lovelaceEvent = e as LovelaceDomEvent;
    if (
        EVENT_LOVELACE_DOM_DETAIL in lovelaceEvent.detail &&
        "action_handler_id" in lovelaceEvent.detail[EVENT_LOVELACE_DOM_DETAIL] &&
        lovelaceEvent.detail[EVENT_LOVELACE_DOM_DETAIL]["action_handler_id"]
        === (card.config.action_handler_id ?? "this")
    ) {
        const details = lovelaceEvent.detail[EVENT_LOVELACE_DOM_DETAIL];
        if (details["action"] === undefined)
            return;
        const action = details["action"] as ActionType;
        const data = details["data"];
        const currentMode = card._getCurrentMode();
        switch (action) {
            case ActionType.CLEANING_START:
                await runSelection(card, false);
                break;
            case ActionType.INTERNAL_VARIABLE_SET:
                setInternalVariable(card, data["variable"], data["value"]);
                break;
            case ActionType.MAP_MODE_NEXT:
                setCurrentMode(card, (card.selectedMode + 1) % card.modes.length, false);
                break;
            case ActionType.MAP_MODE_PREVIOUS:
                setCurrentMode(card, (card.selectedMode - 1 + card.modes.length) % card.modes.length, false);
                break;
            case ActionType.MAP_MODE_SET:
                setCurrentMode(card, data["index"] % card.modes.length, false);
                break;
            case ActionType.MAP_VIEW_RESET:
                card._resetMapView();
                break;
            case ActionType.REPEATS_DECREMENT:
                if (currentMode) {
                    card.repeats = ((card.repeats + currentMode.maxRepeats - 2) % currentMode.maxRepeats) + 1;
                }
                break;
            case ActionType.REPEATS_INCREMENT:
                if (currentMode) {
                    card.repeats = (card.repeats % currentMode.maxRepeats) + 1;
                }
                break;
            case ActionType.REPEATS_SET:
                if (currentMode) {
                    card.repeats = ((data["value"] + currentMode.maxRepeats - 1) % currentMode.maxRepeats) + 1;
                }
                break;
            case ActionType.SELECTION_CLEAR:
                setCurrentMode(card, card.selectedMode);
                break;
        }
    }
}
