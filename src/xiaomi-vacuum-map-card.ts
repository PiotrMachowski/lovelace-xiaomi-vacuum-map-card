    /**
     * The current ROOM mode's configured ids that the live camera metadata no longer contains.
     * An empty list when the mode is not a ROOM mode or the camera exposes no metadata.
     *
     * The audit is deliberately recomputed from the current `hass` instead of trusting the room
     * objects: camera metadata can shift while a selection made against the old metadata is still
     * held, and that stale id must not reach the service call (issue #928).
     */
    private _getStaleRoomIds(mode: MapMode | undefined): string[] {
        if (mode?.selectionType !== SelectionType.ROOM) return [];
        const configuredIds = (mode.predefinedSelections as RoomConfig[])
            .filter(room => room && room.id !== undefined)
            .map(room => room.id);
        return findStaleRoomIds(configuredIds, this._getLiveRooms());
    }

    private _getRoomsConfig(requestId?: string): RoomConfigEventData | undefined {
        const config = this._getCurrentPreset();
        const rooms = this.hass.states[config.map_source?.camera ?? ""]?.attributes["rooms"] as Record<
            string,
            MapExtractorRoom
        >;
        const roomsConfig = new Array<RoomConfig>();
        if (rooms) {
            const mode = this.modes.filter(m => m.selectionType === SelectionType.ROOM).reverse()[0];
            const modeIndex = mode ? this.modes.indexOf(mode) : -1;
            for (const room_id in rooms) {
                if (!rooms.hasOwnProperty(room_id)) continue;
                const room = rooms[room_id];
                const hasBounds = [room.x0, room.y0, room.x1, room.y1].every(value => typeof value === "number");
                if (!room.outline && !hasBounds) continue;
                const outline = room.outline ?? [
                    [room.x0, room.y0],
                    [room.x1, room.y0],
                    [room.x1, room.y1],
                    [room.x0, room.y1],
                ];
                const keepFloat = outline.toString().includes(".");
                const formatCoord = (v: number, divide = 1): number =>
                    keepFloat ? v / divide : Math.round(v / divide);
                const x = outline.reduce((a, v) => a + (v[0] ?? 0), 0);
                const y = outline.reduce((a, v) => a + (v[1] ?? 0), 0);
                const region = this.roomColorDetection?.regions.find(candidate => candidate.id === room_id);
                const detectedCenter = region && this.coordinatesConverter
                    ? this.coordinatesConverter.mapToVacuum(region.center[0], region.center[1])
                    : undefined;

                const roomConfig = {
                    id: room_id,
                    icon: {
                        name: room.icon ?? "mdi:broom",
                        x: room.x ?? detectedCenter?.[0] ?? formatCoord(x, outline.length),
                        y: room.y ?? detectedCenter?.[1] ?? formatCoord(y, outline.length),
                    },
                    label: {
                        text: room.name ?? `Room ${room_id}`,
                        x: room.x ?? detectedCenter?.[0] ?? formatCoord(x, outline.length),
                        y: room.y ?? detectedCenter?.[1] ?? formatCoord(y, outline.length),
                        offset_y: 35,
                    },
                    outline: outline,
                } as RoomConfig;
                roomsConfig.push(roomConfig);
            }
            return {
                modeIndex: modeIndex,
                rooms: roomsConfig,
                entity: config.entity,
                camera: config.map_source?.camera,
                requestId: requestId,
            };
        }
        return undefined;
    }

    private static adjustRoomId(roomId: string | number, config: MapMode): string | number {
        if (config.idType === "number") {
            const roomIdAsNumber = +roomId;
            return isNaN(roomIdAsNumber) ? roomId : roomIdAsNumber;
        }
        return roomId;
    }

    private async _run(debug: boolean): Promise<void> {
        const currentPreset = this._getCurrentPreset();
        const currentMode = this._getCurrentMode();
        const { selection, variables } = this._getSelection(currentMode);
        if ((selection as any[]).length == 0 || !currentMode) {
            this._showToast("popups.no_selection", "mdi:close", false);
            forwardHaptic("failure");
        } else {
            const repeats = this.repeats;
            const entity = currentPreset.entity;
            const runRoomIds =
                currentMode.selectionType === SelectionType.ROOM
                    ? this._getUsableSelectedRooms(currentMode).map(room => String(room.toVacuum()))
                    : [];
            let serviceCall: ServiceCall;
            try {
                serviceCall = await currentMode.getServiceCall(this.hass, currentPreset.entity, selection, repeats, {
                    ...this.internalVariables,
                    ...variables,
                });
            } catch (e) {
                // Nothing was sent, so the selection stays for another attempt.
                this._showToast("popups.failed", "mdi:close", false, (e as Error)?.message);
                forwardHaptic("failure");
                return;
            }
            if (debug || (this.config.debug ?? false)) {
                const message = JSON.stringify(serviceCall, null, 2);
                this._showToast("popups.success", "mdi:check", true);
                console.log(message);
                window.alert(message);
                forwardHaptic("success");
            } else {
                this.hass
                    .callService(serviceCall.domain, serviceCall.service, serviceCall.serviceData, serviceCall.target)
                    .then(
                        () => {
                            this._showToast("popups.success", "mdi:check", true);
                            forwardHaptic("success");
                            if (runRoomIds.length > 0) {
                                this.activeRoomRunEntity = entity;
                                this.activeRoomRun = {
                                    entity,
                                    roomIds: runRoomIds,
                                    startedAt: Date.now(),
                                    seenActive: false,
                                };
                                saveActiveRoomRun(entity, this.activeRoomRun);
                                this.requestUpdate();
                            }
                        },
                        e => {
                            this._showToast("popups.failed", "mdi:close", false, e.message);
                            forwardHaptic("failure");
                        },
                    );
            }
        }
        if (currentPreset.clean_selection_on_start ?? true) {
            this._setCurrentMode(this.selectedMode);
        }
        this._selectionChanged();
    }

    private _updateElements(somethingChanged = false): void {
        const s = this._modesDropdownMenu?.shadowRoot?.querySelector(".dropdown-content") as HTMLElement;
        if (s) {
            s.style.borderRadius = this._getCssProperty("--map-card-internal-big-radius");
        }
        this._scheduleDelayedCallback(() => {
            this._calculateBasicScale();
            this._restoreMapView();
        }, 100);

        if (!somethingChanged) {
            return;
        }

        const update = () => {
            this._setCurrentMode(this.selectedMode);
            this.requestUpdate();
        };

        switch (this._getCurrentMode()?.selectionType) {
            case SelectionType.PREDEFINED_RECTANGLE:
                this.selectablePredefinedRectangles.filter(p => p.isDynamic()).length > 0 && update();
                break;
            case SelectionType.ROOM:
                this.selectedRooms.filter(p => p.isDynamic()).length > 0 && update();
                break;
            case SelectionType.PREDEFINED_POINT:
                this.selectablePredefinedPoints.filter(p => p.isDynamic()).length > 0 && update();
                break;
        }
    }

